export interface PickResult {
  content: string;
  index: number;
}

export function pickContent(layer: NextLayer, usedIndices: readonly number[]): PickResult {
  const pool = BANK[layer];
  const unused = pool.map((_, i) => i).filter((i) => !usedIndices.includes(i));
  const choices = unused.length > 0 ? unused : pool.map((_, i) => i);
  const index = choices[Math.floor(Math.random() * choices.length)];
  return { content: pool[index], index };
}